"""Builds the a2ui skill's reference files from the catalog (skills/a2ui/references/).

The catalog is the single source of truth: the SDK generates the Express grammar and every
component's signature from it, and this script cuts that text into small files the model loads
only when it needs them (see skills/a2ui/SKILL.md). The folder also holds hand-written files
(form.md, chart-choice.md); this script only manages the generated ones. Nothing of it is in the system prompt.

    PYTHONPATH=. python -m app.a2ui.skill_build          # write the files
    PYTHONPATH=. python -m app.a2ui.skill_build --check  # exit 1 if they are out of date

tests/test_a2ui_skill.py runs the check, so a catalog change without a rebuild fails the tests.
"""

import json
import re
import sys
from pathlib import Path

from app.a2ui.catalog import (
    BASIC_COMPONENTS,
    CATALOGS_DIR,
    INSTRUCTIONS,
    PROMPT_SNIPPET,
)

SKILL_DIR = Path(__file__).resolve().parents[2] / "skills" / "a2ui"
REFERENCES = SKILL_DIR / "references"

HEAD = "<!-- Generated by app/a2ui/skill_build.py from the catalog. Do not edit. -->\n"

SIGNATURES = "## Positional Component Signatures"
FUNCTIONS = "## Positional Function Signatures"
CATALOG_INSTRUCTIONS = "## Catalog Instructions"


def _section(start: str, end: str | None) -> str:
    i = PROMPT_SNIPPET.index(start)
    j = PROMPT_SNIPPET.index(end, i) if end else len(PROMPT_SNIPPET)
    return PROMPT_SNIPPET[i:j].strip()


def _signatures() -> tuple[str, dict[str, str]]:
    """The signatures section's intro, and each component's signature block by name."""
    body = _section(SIGNATURES, FUNCTIONS)
    intro, *items = re.split(r"\n(?=• )", body)
    by_name = {re.match(r"• (\w+)\(", item).group(1): item.strip() for item in items}
    return intro.removeprefix(SIGNATURES).strip(), by_name


def build() -> dict[str, str]:
    """{file name: content} for references/."""
    intro, sigs = _signatures()
    files: dict[str, str] = {}

    grammar = PROMPT_SNIPPET[: PROMPT_SNIPPET.index(SIGNATURES)].strip()
    files["grammar.md"] = f"# A2UI Express: output contract and grammar\n\n{grammar}\n"

    basic = "\n\n".join(sigs[name] for name in sorted(BASIC_COMPONENTS))
    files["components.md"] = (
        "# Basic components\n\n"
        "Text, Image, Icon, Row, Column, List, Card, Tabs, Modal, Divider, Video, AudioPlayer, Button,"
        f" TextField, CheckBox, ChoicePicker, Slider, DateTimeInput.\n\n{intro}\n\n{basic}\n"
    )

    functions = _section(FUNCTIONS, CATALOG_INSTRUCTIONS).removeprefix(FUNCTIONS).strip()
    files["functions.md"] = (
        "# Functions: input checks (?required, ?email, ?regex, ...) and formatting\n\n"
        f"{functions}\n"
    )

    files["chart.md"] = f"# VegaChart: charts, graphs and live formulas\n\n{sigs['VegaChart']}\n\n{INSTRUCTIONS}\n"

    for path in sorted((CATALOGS_DIR / "blocks").glob("*.json")):
        doc = json.loads(path.read_text())
        names = list(doc["components"])
        body = "\n\n".join(sigs[n] for n in names)
        files[f"block-{path.stem}.md"] = f"# {', '.join(names)} (chat block)\n\n{body}\n\n{doc['guide']}\n"

    return {name: HEAD + text for name, text in files.items()}


def _generated() -> set[str]:
    """The reference files this script wrote (they start with HEAD). Hand-written ones
    (form.md, chart-choice.md) live in the same folder and are never touched."""
    if not REFERENCES.is_dir():
        return set()
    return {p.name for p in REFERENCES.glob("*.md") if p.read_text().startswith(HEAD)}


def stale() -> list[str]:
    """Reference files that differ from what the catalog generates, or shouldn't exist."""
    want = build()
    have = _generated()
    out = [n for n, text in want.items() if not (REFERENCES / n).is_file() or (REFERENCES / n).read_text() != text]
    return out + sorted(have - set(want))


def write() -> None:
    REFERENCES.mkdir(parents=True, exist_ok=True)
    want = build()
    for name in _generated() - set(want):
        (REFERENCES / name).unlink()
    for name, text in want.items():
        (REFERENCES / name).write_text(text)


if __name__ == "__main__":
    if "--check" in sys.argv:
        bad = stale()
        if bad:
            print("out of date:", ", ".join(bad), "- run: PYTHONPATH=. python -m app.a2ui.skill_build")
            sys.exit(1)
        print("skills/a2ui/references is up to date")
    else:
        write()
        for p in sorted(REFERENCES.glob("*.md")):
            print(f"{p.name}: {len(p.read_text())} chars{'' if p.name in build() else ' (hand-written)'}")
