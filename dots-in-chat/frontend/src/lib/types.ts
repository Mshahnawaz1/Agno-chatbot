export type Metrics = {
  input_tokens?: number
  output_tokens?: number
  total_tokens?: number
  time_to_first_token?: number
  duration?: number
  num_tools?: number
  tools?: { name: string; args: unknown; result: unknown }[]
  [k: string]: unknown
}

/** A knowledge-base chunk a reply drew on. `path` is the workspace copy of its file (null: nothing to open). */
export type Source = { name: string; page: number | null; chunk: number | null; snippet: string; path: string | null }

export type Message = {
  role: 'user' | 'assistant'
  content: string
  metrics?: Metrics | null
  /** Assistant replies since A2UI v1.0: text and A2UI wire messages, in order. */
  parts?: ({ type: 'text'; text: string } | { type: 'a2ui'; message: Record<string, unknown> & { version: string } })[] | null
  /** Assistant replies: knowledge-base chunks the reply drew on. */
  sources?: Source[] | null
  /** Assistant replies: the model's thoughts, if it shared any. */
  reasoning?: string | null
  /** User turns: workspace paths of the files attached to the message. */
  attachments?: string[] | null
  /** User turns started by a click on a surface. */
  action?: {
    name: string
    surfaceId: string
    sourceComponentId: string
    timestamp: string
    context: Record<string, unknown>
  } | null
}

export type Session = {
  id: string
  user_id: string
  title: string | null
  created_at: string
  updated_at: string
}

export type Connector = {
  id: string
  name: string
  notes: string
  url: string
  scopes: string[]
  tools: string[] | null
  connected: boolean
  enabled: boolean
  skill: string | null
}

export type Skill = {
  name: string
  description: string
  allowed_tools: string[]
  instructions: string
}

export type User = {
  id: string
  email: string
  name: string | null
  created_at: string
}

export type FileKind = 'docx' | 'pdf' | 'html' | 'md' | 'xlsx' | 'csv' | 'pptx'
export type FileAction = 'created' | 'updated' | 'deleted' | 'shown'

/** A workspace file the agent touched (SSE `file` event, or derived from stored tool calls). */
export type FileRef = { path: string; kind: FileKind; action: FileAction }

/** `source` is the raw text of a Markdown file, for the editor (absent for other kinds). */
export type FilePreview = { path: string; kind: FileKind; html: string; version: string; source?: string; file?: string }

/** A file in the user's workspace (GET /files): generated by the agent, or uploaded by the user. */
export type FileEntry = {
  path: string
  name: string
  size: number
  modified: string
  kind: FileKind
  origin: 'generated' | 'uploaded'
}
